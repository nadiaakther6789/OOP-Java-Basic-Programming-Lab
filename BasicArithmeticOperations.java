public class BasicArithmeticOperations {
    public static void main(String[] args){  

      int first_number= 125;
      int second_number=24;

       int sum = first_number+second_number;
       int subtract = first_number-second_number;
       int multipication = first_number*second_number;
       int division =  first_number/second_number;
       int modulus =  first_number%second_number;

       System.out.println("Sum:" + sum);
       System.out.println("Subtract:" + subtract);
       System.out.println("multipication:" + multipication);
       System.out.println("division:" + division);
       System.out.println("modulus:" + modulus);
    }
}
