public class ArithmeticOperations {
    public static void main(String[] args){
        int a=5, b=8, c=6, d=55, e=9, f=20, g=3, h=15, i=2;
        int A = -a+b*c;
        int B = (d+e)%e;
        int C = f+ (-g*a)/b;
        int D = a+h/g*i-b%g;

        System.out.println("a." + A);
        System.out.println("b." + B);
        System.out.println("c." + C);
        System.out.println("d." + D);
    }
}
